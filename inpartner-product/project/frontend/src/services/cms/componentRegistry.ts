export function cloneSectionWithFreshIds(section: Partial<CmsSectionNode>, labelOverride?: string): CmsSectionNode {
  const type: SectionType = (section.type && section.type in SECTION_REGISTRY) ? section.type : 'custom_layout';
  const base = SECTION_REGISTRY[type].createDefault();
  const cloned = JSON.parse(JSON.stringify({ ...base, ...section })) as CmsSectionNode;
  cloned.id = generateCmsId(`sec_${type}`);
  cloned.key = generateCmsId(type);
  if (labelOverride) cloned.label = labelOverride;
  if (Array.isArray(cloned.children)) {
    cloned.children = cloned.children.map((ch) => ({
      ...ch,
      id: generateCmsId(`blk_${ch.type}`),
    }));
  } else {
    cloned.children = [];
  }
  return cloned;
}

